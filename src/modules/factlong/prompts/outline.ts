/**
 * The research call: one pass on the web, one plan, one set of numbers.
 *
 * This is the only call in the module that is allowed to look anything up, and
 * that is the design rather than a saving. Ten section calls each free to
 * search would each find a different death toll - the figure on a live
 * disaster moves daily - and the video would contradict itself between minute
 * four and minute eleven without any single call having been wrong.
 *
 * So: everything checkable is settled here, written down with its source and
 * the date it was true, and every later call writes from that list and is told
 * it may not add to it.
 */

export interface OutlinePromptInput {
  projectId: string;
  /** What the project is called before the model has named it properly. */
  workingTitle: string;
  info: ProductInfo | null;
  /** The subject, from the brief. Long-form is never a "pick anything" call. */
  context: string;
  targetDurationSec: number;
  targetWords: number;
  /** Today, so the model can judge what "recent" means and date its figures. */
  today: string;
  channelName: string;
  defaultStyle: string;
  defaultVoice: string;
  /** Titles this channel has already covered, so a video is not a repeat. */
  alreadyCovered: readonly string[];
  /** Pages the person asked for, to be read before anything is searched. */
  sources: readonly string[];
}

